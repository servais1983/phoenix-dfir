def _fw_iptables(p):
    ip = ipaddress.ip_network(p['ip'], strict=False)
    tool = 'ip6tables' if ip.version == 6 else 'iptables'
    addr = sh_quote(str(ip))
    rules = []
    if p['direction'] in ('inbound', 'both'):
        rules.append(f'INPUT -s {addr} -j DROP')
        rules.append(f'FORWARD -s {addr} -j DROP')
    if p['direction'] in ('outbound', 'both'):
        rules.append(f'OUTPUT -d {addr} -j DROP')
        rules.append(f'FORWARD -d {addr} -j DROP')
    pre = (f'command -v {tool} >/dev/null || {{ echo "{tool} not found" >&2; exit 1; }}\n'
           f'[ "$(id -u)" -eq 0 ] || {{ echo "run as root" >&2; exit 1; }}\n'
           f'{tool} -S | grep -F -- {addr} || echo "no existing rule for this address"\n')
    script = ''.join(f'{tool} -C {r} 2>/dev/null || {tool} -I {r}\n' for r in rules)
    script += f'{tool} -S | grep -F -- {addr}\n'
    rollback = ''.join(f'{tool} -D {r} || true\n' for r in rules)
    return pre, script, rollback


def _fw_nftables(p):
    ip = ipaddress.ip_network(p['ip'], strict=False)
    family = 'ip6' if ip.version == 6 else 'ip'
    set_name = 'blocked6' if ip.version == 6 else 'blocked4'
    stype = 'ipv6_addr' if ip.version == 6 else 'ipv4_addr'
    elem = sh_quote('{ ' + str(ip) + ' }')
    pre = ('command -v nft >/dev/null || { echo "nft not found" >&2; exit 1; }\n'
           '[ "$(id -u)" -eq 0 ] || { echo "run as root" >&2; exit 1; }\n'
           'nft list ruleset > /root/phoenix_nft_backup_$(date +%Y%m%d%H%M%S).nft\n')
    script = (
        'nft list table inet phoenix_block >/dev/null 2>&1 || nft add table inet phoenix_block\n'
        f"nft list set inet phoenix_block {set_name} >/dev/null 2>&1 || "
        f"nft add set inet phoenix_block {set_name} '{{ type {stype}; flags interval; }}'\n"
        "nft list chain inet phoenix_block input >/dev/null 2>&1 || "
        "nft add chain inet phoenix_block input '{ type filter hook input priority -10; policy accept; }'\n"
        "nft list chain inet phoenix_block output >/dev/null 2>&1 || "
        "nft add chain inet phoenix_block output '{ type filter hook output priority -10; policy accept; }'\n"
    )
    if p['direction'] in ('inbound', 'both'):
        script += (f"nft list chain inet phoenix_block input | grep -q '{family} saddr @{set_name}' || "
                   f'nft add rule inet phoenix_block input {family} saddr @{set_name} drop\n')
    if p['direction'] in ('outbound', 'both'):
        script += (f"nft list chain inet phoenix_block output | grep -q '{family} daddr @{set_name}' || "
                   f'nft add rule inet phoenix_block output {family} daddr @{set_name} drop\n')
    script += f'nft add element inet phoenix_block {set_name} {elem}\n'
    script += 'nft list table inet phoenix_block\n'
    rollback = (f'nft delete element inet phoenix_block {set_name} {elem}\n'
                '# Remove the whole Phoenix table once no address remains blocked:\n'
                '# nft delete table inet phoenix_block\n')
    return pre, script, rollback


def _fw_windows(p):
    ip = str(ipaddress.ip_network(p['ip'], strict=False))
    safe = ip.replace(':', '-').replace('/', '_')
    rule_in = f'Phoenix-Block-In-{safe}'
    rule_out = f'Phoenix-Block-Out-{safe}'
    pre = (_ps_strict()
           + "if (-not ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent())"
             ".IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) { throw 'Run as Administrator' }\n"
           + "Get-NetFirewallProfile | Select-Object Name, Enabled, DefaultInboundAction, DefaultOutboundAction\n"
           + f"Get-NetFirewallRule -DisplayName {ps_quote('Phoenix-Block-*-' + safe)} -ErrorAction SilentlyContinue\n")
    script = ''
    rollback = ''
    if p['direction'] in ('inbound', 'both'):
        script += (f'if (-not (Get-NetFirewallRule -DisplayName {ps_quote(rule_in)} -ErrorAction SilentlyContinue)) {{\n'
                   f'  New-NetFirewallRule -DisplayName {ps_quote(rule_in)} -Direction Inbound '
                   f'-Action Block -RemoteAddress {ps_quote(ip)} -Profile Any\n}}\n')
        rollback += f'Remove-NetFirewallRule -DisplayName {ps_quote(rule_in)}\n'
    if p['direction'] in ('outbound', 'both'):
        script += (f'if (-not (Get-NetFirewallRule -DisplayName {ps_quote(rule_out)} -ErrorAction SilentlyContinue)) {{\n'
                   f'  New-NetFirewallRule -DisplayName {ps_quote(rule_out)} -Direction Outbound '
                   f'-Action Block -RemoteAddress {ps_quote(ip)} -Profile Any\n}}\n')
        rollback += f'Remove-NetFirewallRule -DisplayName {ps_quote(rule_out)}\n'
    script += ('# Equivalent with netsh (legacy hosts):\n'
               + (f'# netsh advfirewall firewall add rule name="{rule_in}" dir=in action=block remoteip={ip}\n'
                  if p['direction'] in ('inbound', 'both') else '')
               + (f'# netsh advfirewall firewall add rule name="{rule_out}" dir=out action=block remoteip={ip}\n'
                  if p['direction'] in ('outbound', 'both') else ''))
    rollback += f'# netsh: netsh advfirewall firewall delete rule name="{rule_in}" (and {rule_out})\n'
    return pre, script, rollback


def _fw_csv(p):
    ip = str(ipaddress.ip_network(p['ip'], strict=False))
    comment = f"Phoenix DFIR block {p.get('ticket') or ''}".strip()
    header = 'action,direction,source,destination,protocol,port,comment\n'
    port = str(p.get('port') or 'any')
    proto = p.get('protocol') or 'any'
    rows, rb = [], []
    if p['direction'] in ('inbound', 'both'):
        rows.append(['block', 'inbound', ip, 'any', proto, port, comment])
        rb.append(['remove', 'inbound', ip, 'any', proto, port, comment])
    if p['direction'] in ('outbound', 'both'):
        rows.append(['block', 'outbound', 'any', ip, proto, port, comment])
        rb.append(['remove', 'outbound', 'any', ip, proto, port, comment])
    body = header + ''.join(','.join(csv_field(c) for c in r) + '\n' for r in rows)
    rollback = header + ''.join(','.join(csv_field(c) for c in r) + '\n' for r in rb)
    pre = ('# Import into the perimeter firewall management console (or its bulk API).\n'
           '# Check that the address is not a business-critical partner before blocking.\n')
    return pre, body, rollback


