#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Remediation playbooks: templates that generate ready-to-run response
scripts (with pre-checks and rollback) for human approval.

PHOENIX NEVER EXECUTES THESE SCRIPTS. A rendered playbook is attached to a
remediation action (custody.create_remediation), waits for an analyst
decision (WAITING_APPROVAL -> APPROVED / REJECTED, sealed in the chain of
custody with the SHA-256 of the script and of its rollback) and, once
approved, can be downloaded to be run by the response team with its own
tooling and credentials.

Injection safety
----------------
Every parameter is validated against a strict type (ipaddress for IPs and
networks, anchored allow-list regexes for account, host, task, service,
unit names...) and any value containing a shell / PowerShell metacharacter
or a control character is rejected before rendering. Values are then quoted
for their target language (shlex.quote for POSIX shells, single quotes with
doubled quotes for PowerShell, RFC 4180 quoting for CSV), as defense in depth.
"""

import datetime
import ipaddress
import json
import re
import shlex
import urllib.parse

HEADER_NOTICE = ('Generated by Phoenix DFIR for human review. Phoenix NEVER executes this script: '
                 'run it only after approval, with your own tooling and credentials.')

# Characters never accepted in any parameter (shell, PowerShell, cmd, CSV)
_FORBIDDEN = set(';&|`$<>(){}[]!*?~\'"\\%^\n\r\t\x00,=#')
_CONTROL_RE = re.compile(r'[\x00-\x1f\x7f]')

_RE_SAM = re.compile(r'^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$')
_RE_UPN = re.compile(r'^[A-Za-z0-9][A-Za-z0-9._+-]{0,63}@[A-Za-z0-9](?:[A-Za-z0-9-]{0,62}[A-Za-z0-9])?'
                     r'(?:\.[A-Za-z0-9](?:[A-Za-z0-9-]{0,62}[A-Za-z0-9])?)+$')
_RE_HOST = re.compile(r'^(?=.{1,253}$)[A-Za-z0-9](?:[A-Za-z0-9-]{0,62})'
                      r'(?:\.[A-Za-z0-9](?:[A-Za-z0-9-]{0,62}))*$')
_RE_LINUX_USER = re.compile(r'^[a-z_][a-z0-9_-]{0,31}$')
_RE_AWS_KEY = re.compile(r'^(?:AKIA|ASIA)[A-Z0-9]{16}$')
_RE_AWS_USER = re.compile(r'^[A-Za-z0-9._@+-]{1,64}$')
_RE_NAME = re.compile(r'^[A-Za-z0-9][A-Za-z0-9 _.-]{0,127}$')
_RE_TASK_PATH = re.compile(r'^/(?:[A-Za-z0-9 _.-]{1,64}/)*$')
_RE_SERVICE = re.compile(r'^[A-Za-z0-9][A-Za-z0-9_.-]{0,79}$')
_RE_UNIT = re.compile(r'^[A-Za-z0-9][A-Za-z0-9@_.-]{0,120}\.(?:service|timer|socket|path)$')
_RE_CRON_PATTERN = re.compile(r'^[A-Za-z0-9 _./:@+-]{3,200}$')
_RE_SSH_BLOB = re.compile(r'^AAAA[A-Za-z0-9+/]{16,8192}={0,2}$')
_RE_AGENT_ID = re.compile(r'^[A-Za-z0-9][A-Za-z0-9_.:-]{0,127}$')
_RE_TICKET = re.compile(r'^[A-Za-z0-9][A-Za-z0-9_.-]{0,63}$')

_RUN_KEYS = {
    'Run': r'Software\Microsoft\Windows\CurrentVersion\Run',
    'RunOnce': r'Software\Microsoft\Windows\CurrentVersion\RunOnce',
    'Wow6432Node\\Run': r'Software\Wow6432Node\Microsoft\Windows\CurrentVersion\Run',
}


class PlaybookError(ValueError):
    """Invalid template id or parameters. `errors` maps field -> message."""

    def __init__(self, errors):
        self.errors = errors
        super().__init__('; '.join(f'{k}: {v}' for k, v in errors.items()))


