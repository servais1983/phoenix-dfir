def _ad_disable(p):
    ident = ps_quote(p['identity'])
    pre = (_ps_strict() + 'Import-Module ActiveDirectory\n'
           f'$user = Get-ADUser -Identity {ident} -Properties Enabled, LastLogonDate, MemberOf\n'
           '$user | Select-Object SamAccountName, Enabled, LastLogonDate\n'
           "if ($user.SamAccountName -in @('Administrator', 'krbtgt')) { throw 'Refusing built-in account' }\n")
    script = (f'Disable-ADAccount -Identity {ident}\n')
    if p.get('reset_password', True):
        script += ('# Random 32-char password, never displayed nor stored by Phoenix\n'
                   '$bytes = New-Object byte[] 24\n'
                   '[Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)\n'
                   '$plain = [Convert]::ToBase64String($bytes) + \'aA1!\'\n'
                   '$secure = ConvertTo-SecureString $plain -AsPlainText -Force\n'
                   f'Set-ADAccountPassword -Identity {ident} -Reset -NewPassword $secure\n'
                   f'Set-ADUser -Identity {ident} -ChangePasswordAtLogon $true\n'
                   'Remove-Variable plain, secure, bytes\n')
    script += f'Get-ADUser -Identity {ident} -Properties Enabled | Select-Object SamAccountName, Enabled\n'
    rollback = (_ps_strict() + 'Import-Module ActiveDirectory\n'
                f'Enable-ADAccount -Identity {ident}\n'
                '# The password reset cannot be undone: issue a new password through the helpdesk process.\n')
    return pre, script, rollback


def _entra_revoke(p):
    upn = ps_quote(p['upn'])
    pre = (_ps_strict()
           + 'Import-Module Microsoft.Graph.Users, Microsoft.Graph.Users.Actions\n'
           + "Connect-MgGraph -Scopes 'User.ReadWrite.All', 'Directory.AccessAsUser.All' -NoWelcome\n"
           + f'Get-MgUser -UserId {upn} -Property Id, UserPrincipalName, AccountEnabled | '
             'Select-Object Id, UserPrincipalName, AccountEnabled\n')
    script = f'Revoke-MgUserSignInSession -UserId {upn}\n'
    if p.get('disable_account'):
        script += f'Update-MgUser -UserId {upn} -AccountEnabled:$false\n'
    script += f'Get-MgUser -UserId {upn} -Property AccountEnabled | Select-Object AccountEnabled\n'
    rollback = ('# Session revocation is irreversible: the user signs in again after remediation.\n'
                + (f'Update-MgUser -UserId {upn} -AccountEnabled:$true\n' if p.get('disable_account') else ''))
    return pre, script, rollback


