def sh_quote(value):
    return shlex.quote(str(value))


def ps_quote(value):
    """PowerShell single-quoted literal (no expansion; ' doubled)."""
    return "'" + str(value).replace("'", "''") + "'"


def csv_field(value):
    text = str(value)
    if any(c in text for c in ',"\n\r'):
        text = '"' + text.replace('"', '""') + '"'
    return text


