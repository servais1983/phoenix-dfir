_EXTENSIONS = {'bash': 'sh', 'powershell': 'ps1', 'csv': 'csv'}


def list_templates():
    out = []
    for tid, t in TEMPLATES.items():
        out.append({
            'id': tid, 'category': t['category'], 'title': t['title'], 'language': t['language'],
            'description': t['description'], 'mitre_mitigation': t['mitre'],
            'params': [dict(p, type_help=(TYPES[p['type']][1] if p['type'] in TYPES else None))
                       for p in t['params']],
        })
    return out


def validate_params(template_id, raw):
    """Validate and normalise parameters. Raises PlaybookError."""
    template = TEMPLATES.get(template_id)
    if not template:
        raise PlaybookError({'template_id': 'unknown playbook template'})
    if not isinstance(raw, dict):
        raise PlaybookError({'params': 'object expected'})
    known = {p['name'] for p in template['params']}
    errors = {name: 'unknown parameter' for name in raw if name not in known}
    clean = {}
    for spec in template['params']:
        name = spec['name']
        value = raw.get(name)
        if value is None or (isinstance(value, str) and value.strip() == ''):
            if spec['required'] and spec['default'] is None:
                errors[name] = 'required'
            elif spec['default'] is not None:
                clean[name] = spec['default']
            continue
        if not isinstance(value, (str, int, bool)) or (isinstance(value, str) and len(value) > 8192):
            errors[name] = 'invalid value'
            continue
        try:
            if spec['type'] == 'choice':
                clean[name] = _choice(*spec['options'])(value)
            else:
                validator = TYPES[spec['type']][0]
                clean[name] = validator(value if spec['type'] in ('bool', 'port') else str(value))
        except ValueError as e:
            errors[name] = str(e)
    if errors:
        raise PlaybookError(errors)
    return clean


def _target_host(template_id, params):
    for key in ('hostname', 'identity', 'upn', 'aws_user', 'ip', 'agent_id'):
        if params.get(key):
            return str(params[key])
    return template_id


def render(template_id, raw_params):
    """Render a playbook. Returns a dict with script, rollback, prechecks,
    language, filename, summary and target_host. Raises PlaybookError."""
    params = validate_params(template_id, raw_params)
    template = dict(TEMPLATES[template_id], id=template_id)
    prechecks, body, rollback = template['render'](params)
    lang = template['language']
    if lang == 'csv':
        script = body
        rollback_full = rollback
        prechecks_full = prechecks
    else:
        comment = '#'
        strict = _sh_strict() if lang == 'bash' else _ps_strict()
        header = _header(template, params, comment)
        script = (strict + header + f'\n{comment} ---- Pre-checks ----\n' + prechecks.replace(strict, '')
                  + f'\n{comment} ---- Remediation ----\n' + body)
        rollback_full = strict + header + f'\n{comment} ---- Rollback ----\n' + rollback.replace(strict, '')
        prechecks_full = strict + header + f'\n{comment} ---- Pre-checks only ----\n' + prechecks.replace(strict, '')
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%dT%H%M%SZ')
    first_line = next((ln for ln in body.splitlines() if ln and not ln.startswith('#')), template_id)
    return {
        'template_id': template_id,
        'title': template['title'],
        'category': template['category'],
        'language': lang,
        'params': params,
        'script': script,
        'rollback': rollback_full,
        'prechecks': prechecks_full,
        'filename': f'phoenix_{template_id}_{stamp}.{_EXTENSIONS[lang]}',
        'summary': f"[playbook {template_id}] {first_line}"[:1000],
        'target_host': _target_host(template_id, params)[:255],
        'mitre': template['mitre'],
        'executed_by_phoenix': False,
    }
