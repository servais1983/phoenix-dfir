def _edr_isolate(p):
    url = sh_quote(p['api_url'])
    body = json.dumps({'agent_id': p['agent_id'], 'action': 'isolate',
                       'comment': f"Phoenix DFIR containment {p.get('ticket') or ''}".strip()},
                      sort_keys=True)
    rb_body = json.dumps({'agent_id': p['agent_id'], 'action': 'unisolate',
                          'comment': f"Phoenix DFIR release {p.get('ticket') or ''}".strip()},
                         sort_keys=True)
    pre = ('# Generic EDR API placeholder: adapt the endpoint and body to your EDR vendor.\n'
           '# The API token is read from the EDR_API_TOKEN environment variable, never embedded.\n'
           ': "${EDR_API_TOKEN:?export EDR_API_TOKEN first}"\n'
           'command -v curl >/dev/null || { echo "curl not found" >&2; exit 1; }\n')
    script = (f'curl --fail --silent --show-error -X POST {url} \\\n'
              '  -H "Authorization: Bearer ${EDR_API_TOKEN}" -H \'Content-Type: application/json\' \\\n'
              f'  --data {sh_quote(body)}\n')
    rollback = (f'curl --fail --silent --show-error -X POST {url} \\\n'
                '  -H "Authorization: Bearer ${EDR_API_TOKEN}" -H \'Content-Type: application/json\' \\\n'
                f'  --data {sh_quote(rb_body)}\n')
    return pre, script, rollback


def _win_isolate(p):
    mgmt = str(ipaddress.ip_network(p['management_ip'], strict=False))
    host = p['hostname']
    backup = f'C:\\Windows\\Temp\\phoenix_fw_backup_{host}.wfw'
    pre = (_ps_strict()
           + f"if ($env:COMPUTERNAME -ne {ps_quote(host.split('.')[0].upper())}) "
             "{ throw 'This script targets another host' }\n"
           + f'Test-NetConnection -ComputerName {ps_quote(mgmt.split("/")[0])} -InformationLevel Quiet\n'
           + f'netsh advfirewall export {ps_quote(backup)}\n')
    script = (
        f"New-NetFirewallRule -DisplayName 'Phoenix-Isolation-Mgmt-In' -Direction Inbound -Action Allow "
        f'-RemoteAddress {ps_quote(mgmt)} -Profile Any\n'
        f"New-NetFirewallRule -DisplayName 'Phoenix-Isolation-Mgmt-Out' -Direction Outbound -Action Allow "
        f'-RemoteAddress {ps_quote(mgmt)} -Profile Any\n'
        '# Block everything else, in and out, on every profile\n'
        'Set-NetFirewallProfile -Profile Domain, Private, Public -Enabled True '
        '-DefaultInboundAction Block -DefaultOutboundAction Block\n'
        "Get-NetFirewallRule | Where-Object { $_.Action -eq 'Allow' -and $_.DisplayName -notlike "
        "'Phoenix-Isolation-*' -and $_.Enabled -eq 'True' } | Disable-NetFirewallRule\n"
    )
    rollback = (_ps_strict()
                + f'netsh advfirewall import {ps_quote(backup)}\n'
                + "Remove-NetFirewallRule -DisplayName 'Phoenix-Isolation-Mgmt-In', 'Phoenix-Isolation-Mgmt-Out'\n")
    return pre, script, rollback


