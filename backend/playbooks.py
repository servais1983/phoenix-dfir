def _header(template, params, comment='#'):
    lines = [
        f'{comment} Phoenix DFIR remediation playbook: {template["id"]} ({template["title"]})',
        f'{comment} {HEADER_NOTICE}',
        f'{comment} Parameters: {json.dumps(params, sort_keys=True)}',
    ]
    return '\n'.join(lines) + '\n'


