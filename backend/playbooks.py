def _check_chars(value, allow=''):
    if _CONTROL_RE.search(value):
        raise ValueError('control characters are not allowed')
    bad = sorted({c for c in value if c in _FORBIDDEN and c not in allow})
    if bad:
        raise ValueError(f"forbidden character(s): {' '.join(repr(c) for c in bad)}")


def _v_ip(value):
    _check_chars(value)
    return str(ipaddress.ip_address(value.strip()))


def _v_ip_or_cidr(value):
    _check_chars(value)
    value = value.strip()
    if '/' in value:
        return str(ipaddress.ip_network(value, strict=False))
    return str(ipaddress.ip_address(value))


def _regex(pattern, label, allow=''):
    def validate(value):
        _check_chars(value, allow)
        if not pattern.fullmatch(value):
            raise ValueError(f'invalid {label}')
        return value
    return validate


def _v_identity(value):
    """AD sAMAccountName or UPN."""
    _check_chars(value)
    if _RE_SAM.fullmatch(value) or _RE_UPN.fullmatch(value):
        return value
    raise ValueError('invalid account name (sAMAccountName or UPN expected)')


def _v_https_url(value):
    _check_chars(value, allow='')
    if any(c in value for c in ' "\'<>'):
        raise ValueError('invalid URL')
    parsed = urllib.parse.urlparse(value)
    if parsed.scheme != 'https' or not parsed.hostname or parsed.username or parsed.password:
        raise ValueError('an https:// URL without credentials is required')
    if not _RE_HOST.fullmatch(parsed.hostname) and not _is_ip(parsed.hostname):
        raise ValueError('invalid URL host')
    if not re.fullmatch(r'[A-Za-z0-9/._:-]*', parsed.path or '') or parsed.query or parsed.fragment:
        raise ValueError('URL path may only contain letters, digits and / . _ : -')
    return value


def _is_ip(value):
    try:
        ipaddress.ip_address(value)
        return True
    except ValueError:
        return False


def _choice(*options):
    def validate(value):
        if value not in options:
            raise ValueError(f"must be one of: {', '.join(options)}")
        return value
    validate.options = options
    return validate


def _v_port(value):
    if isinstance(value, bool):
        raise ValueError('invalid port')
    try:
        port = int(str(value).strip())
    except ValueError as e:
        raise ValueError('invalid port') from e
    if not 1 <= port <= 65535:
        raise ValueError('port must be between 1 and 65535')
    return port


def _v_bool(value):
    if isinstance(value, bool):
        return value
    if str(value).lower() in ('1', 'true', 'yes', 'on'):
        return True
    if str(value).lower() in ('0', 'false', 'no', 'off', ''):
        return False
    raise ValueError('boolean expected')


