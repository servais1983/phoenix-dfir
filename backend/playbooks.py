def _sched_task(p):
    name = ps_quote(p['task_name'])
    backup = ps_quote(f"C:\\Windows\\Temp\\phoenix_task_{p['task_name'].replace(' ', '_')}.xml")
    ps_path = (p.get('task_path') or '/').replace('/', '\\')
    path = ps_quote(ps_path)
    pre = (_ps_strict()
           + f'$task = Get-ScheduledTask -TaskName {name} -TaskPath {path}\n'
           + '$task.Actions | Format-List *\n'
           + f'Export-ScheduledTask -TaskName {name} -TaskPath {path} | Out-File -Encoding UTF8 {backup}\n')
    script = (f'Disable-ScheduledTask -TaskName {name} -TaskPath {path}\n'
              f'Unregister-ScheduledTask -TaskName {name} -TaskPath {path} -Confirm:$false\n')
    rollback = (f'Register-ScheduledTask -TaskName {name} -TaskPath {path} '
                f'-Xml (Get-Content -Raw {backup})\n')
    return pre, script, rollback


def _service(p):
    svc = ps_quote(p['service_name'])
    backup = ps_quote(f"C:\\Windows\\Temp\\phoenix_service_{p['service_name']}.json")
    pre = (_ps_strict()
           + f"$svc = Get-CimInstance Win32_Service -Filter (\"Name='{{0}}'\" -f {svc})\n"
           + "if (-not $svc) { throw 'Service not found' }\n"
           + '$svc | Select-Object Name, DisplayName, State, StartMode, PathName, StartName\n'
           + f'$svc | Select-Object Name, StartMode, PathName, StartName | ConvertTo-Json | '
             f'Out-File -Encoding UTF8 {backup}\n')
    script = (f'Stop-Service -Name {svc} -Force\n'
              f'Set-Service -Name {svc} -StartupType Disabled\n')
    if p.get('delete_service'):
        script += f'sc.exe delete {ps_quote(p["service_name"])}\n'
    rollback = (_ps_strict() + f'$saved = Get-Content -Raw {backup} | ConvertFrom-Json\n')
    if p.get('delete_service'):
        rollback += (f'New-Service -Name {svc} -BinaryPathName $saved.PathName -StartupType Manual\n')
    rollback += ("$mode = @{ 'Auto' = 'Automatic'; 'Manual' = 'Manual'; 'Disabled' = 'Disabled' }[$saved.StartMode]\n"
                 f'Set-Service -Name {svc} -StartupType $mode\n')
    return pre, script, rollback


def _run_key(p):
    hive = 'HKLM' if p['hive'] == 'HKLM' else 'HKCU'
    sub = _RUN_KEYS[p['run_key']]
    ps_path = ps_quote(f'{hive}:\\{sub}')
    reg_path = f'{hive}\\{sub}'
    value = ps_quote(p['value_name'])
    backup = f"C:\\Windows\\Temp\\phoenix_runkey_{p['value_name'].replace(' ', '_')}.reg"
    pre = (_ps_strict()
           + f'Get-ItemProperty -Path {ps_path} -Name {value}\n'
           + f'reg.exe export {ps_quote(reg_path)} {ps_quote(backup)} /y\n')
    script = f'Remove-ItemProperty -Path {ps_path} -Name {value}\n'
    rollback = f'reg.exe import {ps_quote(backup)}\n'
    return pre, script, rollback


def _wmi_sub(p):
    name = ps_quote(p['subscription_name'])
    backup = ps_quote(f"C:\\Windows\\Temp\\phoenix_wmi_{p['subscription_name'].replace(' ', '_')}.xml")
    ns = "-Namespace 'root\\subscription'"
    pre = (_ps_strict()
           + f'$filter = Get-CimInstance {ns} -ClassName __EventFilter | Where-Object Name -eq {name}\n'
           + f'$consumer = Get-CimInstance {ns} -ClassName __EventConsumer | Where-Object Name -eq {name}\n'
           + f'$binding = Get-CimInstance {ns} -ClassName __FilterToConsumerBinding | '
             'Where-Object { $_.Filter.Name -eq $filter.Name }\n'
           + "if (-not $filter -and -not $consumer) { throw 'Subscription not found' }\n"
           + f'@{{ Filter = $filter; Consumer = $consumer; Binding = $binding }} | Export-Clixml {backup}\n')
    script = ('$binding | Remove-CimInstance\n'
              '$consumer | Remove-CimInstance\n'
              '$filter | Remove-CimInstance\n'
              f'Get-CimInstance {ns} -ClassName __EventFilter | Where-Object Name -eq {name}\n')
    rollback = ('# WMI objects cannot be re-imported automatically: the backup holds their full\n'
                '# definition (query, consumer command line) to recreate them if needed.\n'
                f'$saved = Import-Clixml {backup}\n'
                '$saved.Filter | Format-List *\n$saved.Consumer | Format-List *\n')
    return pre, script, rollback


def _cron(p):
    user = sh_quote(p['linux_user'])
    pattern = sh_quote(p['pattern'])
    backup = f"/root/phoenix_crontab_{p['linux_user']}.bak"
    pre = ('[ "$(id -u)" -eq 0 ] || { echo "run as root" >&2; exit 1; }\n'
           f'crontab -l -u {user} > {sh_quote(backup)}\n'
           f'grep -nF -- {pattern} {sh_quote(backup)} || {{ echo "pattern not found" >&2; exit 1; }}\n'
           'grep -rnF -- ' + pattern + ' /etc/cron* /etc/crontab 2>/dev/null || true\n')
    script = (f'grep -vF -- {pattern} {sh_quote(backup)} | crontab -u {user} -\n'
              f'crontab -l -u {user}\n')
    rollback = f'crontab -u {user} {sh_quote(backup)}\n'
    return pre, script, rollback


def _systemd(p):
    unit = sh_quote(p['unit'])
    backup = f"/root/phoenix_unit_{p['unit']}.bak"
    pre = ('[ "$(id -u)" -eq 0 ] || { echo "run as root" >&2; exit 1; }\n'
           f'systemctl status {unit} --no-pager || true\n'
           f'systemctl cat {unit} > {sh_quote(backup)}\n'
           f'systemctl show {unit} -p FragmentPath,UnitFileState,ActiveState\n')
    script = (f'systemctl stop {unit}\n'
              f'systemctl disable {unit}\n'
              f'systemctl mask {unit}\n'
              'systemctl daemon-reload\n')
    rollback = (f'systemctl unmask {unit}\n'
                f'systemctl enable {unit}\n'
                f'systemctl start {unit}\n'
                f'# Unit definition saved in {backup}\n')
    return pre, script, rollback


def _authorized_keys(p):
    user = sh_quote(p['linux_user'])
    blob = sh_quote(p['key_blob'])
    backup = f"/root/phoenix_authorized_keys_{p['linux_user']}.bak"
    pre = ('[ "$(id -u)" -eq 0 ] || { echo "run as root" >&2; exit 1; }\n'
           f'HOME_DIR="$(getent passwd {user} | cut -d: -f6)"\n'
           '[ -n "$HOME_DIR" ] || { echo "user not found" >&2; exit 1; }\n'
           'AK="$HOME_DIR/.ssh/authorized_keys"\n'
           f'grep -nF -- {blob} "$AK" || {{ echo "key not found" >&2; exit 1; }}\n'
           f'cp -p "$AK" {sh_quote(backup)}\n')
    script = (f'grep -vF -- {blob} {sh_quote(backup)} > "$AK.phoenix.tmp"\n'
              'chown --reference="$AK" "$AK.phoenix.tmp"\n'
              'chmod --reference="$AK" "$AK.phoenix.tmp"\n'
              'mv "$AK.phoenix.tmp" "$AK"\n'
              f'grep -cF -- {blob} "$AK" || true\n')
    rollback = (f'HOME_DIR="$(getent passwd {user} | cut -d: -f6)"\n'
                f'cp -p {sh_quote(backup)} "$HOME_DIR/.ssh/authorized_keys"\n')
    return pre, script, rollback


